//! `revised-sdk lint`: Presto/ES5 and package checks. `build` runs this first.
//! Columns are 1-based and counted in characters (not bytes).
mod css;
mod es5;
mod pkg;

use crate::modyaml;
use crate::report::{Finding, Level};
use std::path::Path;

fn walk(dir: &Path, rel: &str, out: &mut Vec<String>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        let r = if rel.is_empty() { name } else { format!("{rel}/{name}") };
        if e.file_type().is_ok_and(|t| t.is_dir()) {
            walk(&e.path(), &r, out);
        } else {
            out.push(r);
        }
    }
}

/// 1-based (line, col) of char index `idx`; `starts` = char index of each line start.
fn locate(starts: &[usize], idx: usize) -> (u32, u32) {
    let l = starts.partition_point(|&s| s <= idx);
    (l as u32, (idx - starts[l - 1] + 1) as u32)
}

fn line_starts(c: &[char]) -> Vec<usize> {
    std::iter::once(0).chain(c.iter().enumerate().filter(|(_, x)| **x == '\n').map(|(i, _)| i + 1)).collect()
}

pub fn has_errors(f: &[Finding]) -> bool {
    f.iter().any(|x| x.level == Level::Error)
}

pub fn run(dir: &Path) -> Vec<Finding> {
    let m = match modyaml::load(dir) {
        Ok(m) => m,
        Err(f) => return f,
    };
    let ui = dir.join("ui");
    let mut files = Vec::new();
    walk(&ui, "", &mut files);
    files.sort();
    let (mut out, mut registered) = (Vec::new(), false);
    for rel in &files {
        let ext = rel.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
        if !matches!(ext.as_str(), "js" | "css" | "html" | "htm") {
            continue;
        }
        let path = format!("ui/{rel}");
        let bytes = match std::fs::read(ui.join(rel)) {
            Ok(b) => b,
            Err(e) => {
                out.push(Finding::error("io", &format!("{path}: {e}")));
                continue;
            }
        };
        let text = match String::from_utf8(bytes) {
            Ok(t) => t,
            Err(e) => {
                let ok = e.utf8_error().valid_up_to();
                let pre: Vec<char> = String::from_utf8_lossy(&e.as_bytes()[..ok]).chars().collect();
                let (l, col) = locate(&line_starts(&pre), pre.len());
                out.push(Finding::error("encoding", "file is not valid UTF-8; skipped").at(&path, l, col));
                continue;
            }
        };
        let c: Vec<char> = text.chars().collect();
        let starts = line_starts(&c);
        let mut hit = |f: Finding, idx: usize| {
            let (l, col) = locate(&starts, idx);
            out.push(f.at(&path, l, col));
        };
        for i in pkg::ws_literals(&c) {
            hit(Finding::warning("ws-literal-port", "hard-coded WebSocket port: take the endpoint from the HMI framework"), i);
        }
        match ext.as_str() {
            "js" => {
                registered |= pkg::registers(&c, &m.name);
                for (i, msg) in es5::scan(&c) {
                    hit(Finding::error("es5-syntax", msg), i);
                }
            }
            "css" => {
                for (i, msg) in css::scan(&c) {
                    hit(Finding::error("css-presto", &msg), i);
                }
            }
            _ => {
                for (s, e) in css::style_attrs(&c) {
                    for (i, msg) in css::scan(&c[s..e]) {
                        hit(Finding::error("css-presto", &msg), s + i);
                    }
                }
            }
        }
    }
    if m.app.is_some() && !registered {
        out.push(pkg::no_register(&m.name));
    }
    if ui.join("hmi.json").is_file() {
        let w = Finding::warning("hmi-handwritten", "ui/hmi.json is generated by `build`; your copy will be overwritten");
        out.push(Finding { file: Some("ui/hmi.json".into()), ..w });
    }
    out
}
